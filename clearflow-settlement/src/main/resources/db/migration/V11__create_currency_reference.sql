CREATE TABLE CF_CURRENCY_REFERENCE
(
    CURRENCY_CODE      VARCHAR2(3)                    NOT NULL,
    CURRENCY_NAME      VARCHAR2(100)                  NOT NULL,
    SYMBOL             VARCHAR2(20),
    DECIMAL_DIGITS     NUMBER(1,0)                    NOT NULL,
    CURRENCY_TYPE      VARCHAR2(20)                   NOT NULL,
    SUPPORTED          NUMBER(1,0) DEFAULT 0          NOT NULL,
    PROVIDER           VARCHAR2(50)                   NOT NULL,
    LAST_SYNCED_AT     TIMESTAMP(6) WITH TIME ZONE    NOT NULL,
    CREATED_AT         TIMESTAMP(6) WITH TIME ZONE    NOT NULL,
    UPDATED_AT         TIMESTAMP(6) WITH TIME ZONE    NOT NULL,
    VERSION_NO         NUMBER(10,0) DEFAULT 0          NOT NULL,

    CONSTRAINT PK_CF_CURRENCY_REFERENCE
        PRIMARY KEY (CURRENCY_CODE),

    CONSTRAINT CK_CF_CURR_SUPPORTED
        CHECK (SUPPORTED IN (0, 1)),

    CONSTRAINT CK_CF_CURR_DECIMAL_DIGITS
        CHECK (DECIMAL_DIGITS BETWEEN 0 AND 9)
);